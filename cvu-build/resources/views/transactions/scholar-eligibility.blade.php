    <h2 id="scholar-eligibility-title">Scholarship discount eligibility</h2>
    <ul>
        <li>Be enrolled at Urdaneta City University and have your registration form ready.</li>
        <li>First-year students need Form 137 or Form 138. Continuing students need previous grades of at least 81%.</li>
        <li>Prepare the scholarship application form from CSLD and both 1×1 and 2×2 ID photos with a white background.</li>
        <li>Check the grant you are applying for. Some grants require additional proof or have stricter grade requirements. You can receive one scholarship grant at a time.</li>
    </ul>
    <p><a href="https://www.ucu.edu.ph/page/student-services-scholarship-grants">View UCU’s requirements for each grant</a></p>
</section>
